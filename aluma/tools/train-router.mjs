// Teaches Aluma's fast-answer router from the teaching list (tests/teach-list.mjs) and writes its seed
// knowledge to js/router-seed.js – the same safe learning Gemini uses (word stems + a topic, never
// sentences; meaning-changing, sensitive and name words are never learned). Then it guards the result:
// any learned word that makes a question meant for the language model "fast" is removed.
// Run from the repo root:  node aluma/tools/train-router.mjs
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
globalThis.localStorage = { getItem: () => null, setItem() {}, removeItem() {} };
globalThis.sessionStorage = globalThis.localStorage;
const OUT = join(dirname(fileURLToPath(import.meta.url)), '..', 'js', 'router-seed.js');
writeFileSync(OUT, 'export const SEED = {};\n');                 // train from a clean slate
const E = await import('../js/engine.js');
const { buildContext } = await import('../js/auth.js');
const { db } = await import('../js/store.js');
const { TEACH, FRESH } = await import('../tests/teach-list.mjs');
const { CORPUS } = await import('../tests/router-corpus.mjs');
const { HOLDOUT } = await import('../tests/router-holdout.mjs');
const { generate } = await import('../tests/question-bank.mjs');
const TOOL = { grades: 'get_grades', average: 'get_grades', assignments: 'get_assignments', schedule: 'get_schedule', attendance: 'get_attendance', announcements: 'get_announcements', progress: 'get_my_progress', teachers: 'list_my_teachers' };

const score = () => { let ok = 0, n = 0, wrong = 0; for (const [uid, rows] of Object.entries(FRESH)) { const c = buildContext(uid); for (const [q, t] of rows) { n++; const r = E.routeQuestion(c, q); if (t === 'ai' ? !r.intent : r.intent === t) ok++; else if (t === 'ai') wrong++; } } return `${ok}/${n} correct, ${wrong} fast answers to AI questions`; };
const before = score();
let taught = 0, already = 0, refused = 0;
for (const [uid, rows] of Object.entries(TEACH)) {
  const ctx = buildContext(uid);
  for (const [q, topic] of rows) {
    if (topic === 'ai' || !TOOL[topic]) continue;
    const r = E.routeQuestion(ctx, q);
    if (r.intent === topic) { already++; continue; }
    if (E.rememberHit(ctx, q, topic)) taught++; else refused++;
  }
}
// guard: every question meant for the language model (in all lists) must still go there
const aiRows = [];
for (const set of [TEACH, CORPUS, HOLDOUT]) for (const [uid, rows] of Object.entries(set)) for (const [q, t] of rows) if (t === 'ai') aiRows.push([uid, q]);
for (const x of generate({ split: 'all' })) if (x.topic === 'ai') aiRows.push([x.uid, x.q]);
const vocab = db().routerLearn.vocab; let removed = [];
for (let round = 0; round < 5; round++) {
  const bad = aiRows.filter(([uid, q]) => E.routeQuestion(buildContext(uid), q).intent);
  if (!bad.length) break;
  for (const [uid, q] of bad) {
    const words = E.canonical(q).split(' ');
    for (const [it, v] of Object.entries(vocab)) for (const k of Object.keys(v)) if (words.some(w => w.includes(k.replace(/^~/, '').slice(0, 3)))) { if (v[k] > 0) removed.push(`${k}→${it} (because of "${q}")`); v[k] = 0; }
  }
}
const SEED = {};
for (const [it, v] of Object.entries(vocab)) { const keys = Object.keys(v).filter(k => v[k] > 0).sort(); if (keys.length) SEED[it] = keys; }
const total = Object.values(SEED).reduce((a, k) => a + k.filter(x => !x.startsWith('~')).length, 0);
writeFileSync(OUT, `// Seed knowledge of the fast-answer router – generated by tools/train-router.mjs from tests/teach-list.mjs.
// Word stems (and ~skeletons) per topic. Do not edit by hand: change the teaching list and run the trainer.
export const SEED = ${JSON.stringify(SEED, null, 1).replace(/\n\s*/g, ' ')};
`);
console.log(`taught from ${taught} questions (${already} were already fast, ${refused} refused by the safety rules) → ${total} words in ${Object.keys(SEED).length} topics`);
console.log(Object.entries(SEED).map(([it, k]) => `  ${it}: ${k.filter(x => !x.startsWith('~')).join(', ')}`).join('\n'));
console.log(`fresh questions (not in the teaching list): before ${before} → after ${score()}`);
if (removed.length) console.log('removed by the guard:\n  ' + [...new Set(removed)].join('\n  '));
